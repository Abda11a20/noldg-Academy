export interface GlyphRendererProps extends LucideProps {
  name: Exclude<IconName, "globe">;
}

/** Renders the requested non-shell Lucide glyph after its lazy chunk has loaded.
 * @param props Registry name and Lucide SVG properties.
 */
export default function GlyphRenderer({ name, ...props }: GlyphRendererProps) {
  const Glyph = glyphs[name];
  return <Glyph {...props} />;
}
